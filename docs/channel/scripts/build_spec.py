#!/usr/bin/env python3
"""build_spec.py - one short, generated build spec from the atelier build's JSON artifacts.

    python3 docs/channel/scripts/build_spec.py projects/<id>          # writes artifacts/BUILD_SPEC.md
    python3 docs/channel/scripts/build_spec.py projects/<id> --stdout

Builders and QA agents read this (~200 lines) instead of BUILD.md's prose plus timeline.json, props.json (170 KB),
soundtrack_report.json and scene_plan.json. Everything here is derived, nothing is typed by hand, so the spec cannot
drift from the build: re-run it after every build_props.py / build_soundtrack.py run (build_props.py may call it).

Sections: film, sections and scenes (with the narration under each), caption pages, the honesty tab's state changes,
claim graphics (placards and the plate window), key frames, SFX cues, every animated channel's active ranges (generic:
any list of numbers in props), the ending, and the frames a QA agent should look at (page starts, seams, window
opens/closes, release). BUILD.md stays for the contract (component APIs, rules, divergences); it should no longer
repeat the numbers in here.
"""
import argparse, json, sys
from pathlib import Path


def jload(p):
    return json.load(open(p)) if Path(p).exists() else {}


def fs(f, fps):
    return f"f{f} ({f / fps:.2f} s)"


def ranges(seq, eps=1e-9):
    """[(first, last)] frames where a numeric channel is non-zero (gaps of < 3 frames are merged)."""
    out = []
    cur = None
    for i, v in enumerate(seq):
        on = abs(float(v)) > eps
        if on and cur is None:
            cur = [i, i]
        elif on:
            cur[1] = i
        elif cur is not None and i - cur[1] > 2:
            out.append(tuple(cur))
            cur = None
    if cur is not None:
        out.append(tuple(cur))
    return out


def changes(seq):
    """frames where an integer/step channel changes value: [(frame, new_value)]"""
    out = []
    prev = None
    for i, v in enumerate(seq):
        if v != prev:
            if prev is not None:
                out.append((i, v))
            prev = v
    return out


def channel_rows(obj, path, fps, rows, max_depth=3):
    if isinstance(obj, dict):
        for k, v in obj.items():
            if max_depth > 0:
                channel_rows(v, f"{path}.{k}" if path else k, fps, rows, max_depth - 1)
    elif isinstance(obj, list) and obj and all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in obj) and len(obj) > 60:
        vals = set(obj)
        if len(vals) <= 12 and all(float(x).is_integer() for x in obj):
            ch = changes(obj)
            if not ch:
                rows.append((path, f"constant {obj[0]:g}"))
            else:
                rows.append((path, f"starts {obj[0]:g}; steps " + ", ".join(f"f{f}->{int(v)}" for f, v in ch[:14]) + (" …" if len(ch) > 14 else "")))
        else:
            r = ranges(obj)
            peak = max(abs(float(x)) for x in obj)
            rows.append((path, f"active {', '.join(f'f{a}-{b}' for a, b in r[:8])}{' …' if len(r) > 8 else ''}; peak {peak:g}"))
    elif isinstance(obj, list) and obj and isinstance(obj[0], dict) and max_depth > 0:
        for i, v in enumerate(obj[:12]):
            channel_rows(v, f"{path}[{v.get('id', i)}]", fps, rows, max_depth - 1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("project")
    ap.add_argument("--stdout", action="store_true")
    a = ap.parse_args()
    P = Path(a.project)
    A = P / "artifacts"
    tl, props, sr, plan, script = (jload(A / f) for f in ("timeline.json", "props.json", "soundtrack_report.json", "scene_plan.json", "script.json"))
    if not tl or not props:
        sys.exit("need artifacts/timeline.json and props.json (run build_props.py first)")
    fps = tl["fps"]
    L = []
    w = L.append
    title = script.get("title") or (plan.get("metadata") or {}).get("title") or P.name
    w(f"# BUILD_SPEC: {title}")
    w(f"Generated by docs/channel/scripts/build_spec.py from artifacts/*.json. Do not edit; re-run after build_props.py / build_soundtrack.py.")
    w("")
    stem_k = next((k for k in tl if k.endswith("_end_frame") and not k.startswith("voice")), None)
    rel_f = tl.get(stem_k) if stem_k else None
    w("## Film")
    w(f"- {tl['width']}x{tl['height']} @ {fps} fps, {tl['total_frames']} f = {tl['total_frames'] / fps:.2f} s; lead {tl.get('lead_frames', round(float(tl.get('lead_seconds', 0)) * fps))} f; "
      f"release {fs(rel_f, fps) if rel_f else '?'}; chord {fs(props.get('settle', {}).get('chordFrame', 0), fps)}; settle {tl.get('settle_seconds', '?')} s.")
    if props.get("motion"):
        w("- motion constants (frames): " + ", ".join(f"{k} {v}" for k, v in props["motion"].items()))
    w("")
    w("## Sections and scenes (frame boundaries are absolute; a scene = `from` .. `from + durationInFrames - 1`)")
    words = tl.get("words", [])
    plan_by_id = {s["id"]: s for s in plan.get("scenes", [])}
    for s in tl["sections"]:
        s_words = [x for x in words if x["section"] == s["id"]]
        w(f"- **{s['id']}** f{s['from']}-{s['from'] + s['durationInFrames'] - 1}: \"{' '.join(x['text'] for x in s_words)}\"")
    w("")
    w("| scene | section | from | to | frames | first words | plan (first sentence) |")
    w("|---|---|---|---|---|---|---|")
    for sc in tl["scenes"]:
        f0, f1 = sc["from"], sc["from"] + sc["durationInFrames"] - 1
        pw = [x for x in props.get("captionPages", []) if f0 <= x["startFrame"] <= f1]
        first = " ".join(x["text"] for x in pw[0]["words"][:4]) if pw else ""
        desc = (plan_by_id.get(sc["id"], {}).get("description") or "").split(". ")[0][:110]
        w(f"| {sc['id']} | {sc['section']} | {f0} | {f1} | {sc['durationInFrames']} | {first} | {desc} |")
    w("")
    w("## Caption pages (startFrame = first word onset; exitFrame = page leaves)")
    for i, pg in enumerate(props.get("captionPages", []), 1):
        txt = " ".join(x["text"] for x in pg["words"])
        tones = {x["tone"] for x in pg["words"] if x.get("tone") and x["tone"] != "plain"}
        w(f"- p{i} f{pg['startFrame']}-{pg['exitFrame']} ({pg['section']}): \"{txt}\"" + (f" [{', '.join(sorted(tones))}]" if tones else ""))
    w("")
    w("## Honesty tab (meter): state changes; the glide starts at glideStart and settles 8 f after frame")
    for m in props.get("meter", []):
        w(f"- f{m['frame']} (glide {m.get('glideStart')}): {m['state']}{' / ' + m['sublabel'] if m.get('sublabel') else ''} — {m.get('claim', '')}; anchor: {m.get('anchor', '')}")
    w("")
    w("## Claim graphics (must be gone >= 6 f before the next glide: lessons 42/52)")
    for i, pl in enumerate(props.get("placards", []), 1):
        w(f"- placard {i} f{pl['enter']}-{pl['exit']} ({pl.get('anchor', '')}): \"{pl['line']}\"" + (f" / fine: \"{pl['fine']}\"" if pl.get("fine") else ""))
    win = props.get("window") or {}
    if isinstance(win.get("open"), list):
        r = ranges(win["open"], eps=0.05)
        w(f"- window box {win.get('box')}: open " + ", ".join(f"f{a}-{b}" for a, b in r))
        for pl in win.get("plates", []):
            rr = ranges(pl.get("alpha", []), eps=0.05)
            w(f"  - plate {pl.get('id')} ({pl.get('scene')}): visible " + ", ".join(f"f{a}-{b}" for a, b in rr) + f"; tag \"{pl.get('tag', '')}\"" + ("; PLACEHOLDER" if pl.get("placeholder") else ""))
    w("")
    w("## Key frames (props.audio == soundtrack_report.frames; qa_auto asserts this)")
    fr = sr.get("frames") or props.get("audio", {})
    w("- " + "; ".join(f"{k} {v}" for k, v in fr.items() if k != "soundtrack"))
    w("")
    w("## SFX cues (soundtrack_report.sfx; landing within 1 f of the key frame; phone-band hit >= +4 dB over the bed: lessons 4/5)")
    for c in sr.get("sfx", []):
        fb = c.get("final_phone_band_dbfs") or {}
        w(f"- {c.get('id')} {c.get('name')} f{c.get('frame')} at {c.get('placed_at_s')} s, {c.get('landing')} gain {c.get('peak_dbfs')} dB; "
          f"band sfx {fb.get('sfx')} bed {fb.get('bed')} voice {fb.get('voice')}; hit30 over bed {fb.get('hit_30ms_sfx_over_bed_db')}")
    w("")
    w("## Animated channels (every numeric curve in props; active = non-zero frames; steps = value changes)")
    rows = []
    for k, v in props.items():
        if k in ("timeline", "captionPages", "meter", "placards", "audio", "motion", "labels", "freezes"):
            continue
        channel_rows(v, k, fps, rows)
    for path, desc in rows:
        w(f"- `{path}`: {desc}")
    if props.get("labels"):
        w("- labels: " + "; ".join(f"{k}=\"{v}\"" for k, v in props["labels"].items()))
    w("")
    end = sr.get("ending") or {}
    w("## Ending (finished line: lessons 25/26/43)")
    w(f"- release {end.get('release_s')} s f{end.get('release_frame')}; chord {end.get('chord_film_s')} s f{end.get('chord_frame')} "
      f"({end.get('chord_after_release_s')} s after); settle after chord {end.get('settle_after_chord_s')} s; closing margin {end.get('closing_min_margin_db')} dB; "
      f"CTA f{props.get('cta', {}).get('frame')}: \"{props.get('cta', {}).get('text', '')}\"")
    w(f"- soundtrack {sr.get('soundtrack_lufs')} LUFS, TP {sr.get('soundtrack_true_peak_dbfs')} dBTP (master is re-measured by finish_master.sh / qa_auto.py)")
    w("")
    w("## Frames a QA agent should look at (everything else is measured by qa_auto.py)")
    pages = [pg["startFrame"] for pg in props.get("captionPages", [])]
    seams = [sc["from"] for sc in tl["scenes"][1:]]
    wins = [f for a, b in (ranges(win["open"], eps=0.05) if isinstance(win.get("open"), list) else []) for f in (a, b)]
    glides = [m["glideStart"] for m in props.get("meter", []) if m.get("glideStart")]
    w(f"- page starts: {pages}")
    w(f"- scene seams (b-1 vs b): {seams}")
    w(f"- window opens/closes: {wins}")
    w(f"- tab glides: {glides}")
    w(f"- release and settle: {rel_f}, {props.get('settle', {}).get('chordFrame')}, {tl['total_frames'] - 1}")
    w("- Judge only what a script cannot: anatomy and drawn detail, a visual that contradicts a fact, readability at 360x640, a label under the wrong number (lesson 33), taste.")
    text = "\n".join(L) + "\n"
    if a.stdout:
        sys.stdout.write(text)
    else:
        (A / "BUILD_SPEC.md").write_text(text, encoding="utf-8")
        print(f"wrote {A / 'BUILD_SPEC.md'} ({len(L)} lines)")


if __name__ == "__main__":
    main()
